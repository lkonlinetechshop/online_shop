// ==========================================
// ADD TO CART FUNCTION
// ==========================================

function addToCart() {

    if (!product) {

        alert(
            "Product not found!"
        );

        return;

    }


    // --------------------------------------
    // GET QUANTITY
    // --------------------------------------

    const quantityInput =
        document.getElementById(
            "quantity"
        );


    const quantity =
        parseInt(
            quantityInput.value
        ) || 1;


    // --------------------------------------
    // GET SELECTED OPTION
    // --------------------------------------

    const selectedSizeInput =
        document.querySelector(
            'input[name="bitSize"]:checked'
        );


    let selectedSize = "";

    let selectedProductPrice =
        product.price;


    // --------------------------------------
    // ONLY USE OPTION IF PRODUCT HAS OPTIONS
    // --------------------------------------

    if (
        product.options &&
        product.options.length > 0 &&
        selectedSizeInput
    ) {

        selectedSize =
            selectedSizeInput.value;


        selectedProductPrice =
            Number(
                selectedSizeInput.dataset.price
            );

    }


    // --------------------------------------
    // GET CART
    // --------------------------------------

    let cart =
        JSON.parse(
            localStorage.getItem("cart")
        ) || [];


    // --------------------------------------
    // FIND SAME PRODUCT + SAME SIZE
    // --------------------------------------

    const existingProduct =
        cart.find(function(item) {

            return (

                item.id === product.id &&

                item.size === selectedSize

            );

        });


    // --------------------------------------
    // UPDATE EXISTING PRODUCT
    // --------------------------------------

    if (existingProduct) {

        existingProduct.quantity +=
            quantity;

    }


    // --------------------------------------
    // ADD NEW PRODUCT
    // --------------------------------------

    else {

        cart.push({

            id: product.id,

            name: product.name,

            price: selectedProductPrice,

            image: product.image,

            size: selectedSize,

            quantity: quantity

        });

    }


    // --------------------------------------
    // SAVE CART
    // --------------------------------------

    localStorage.setItem(
        "cart",
        JSON.stringify(cart)
    );


    // --------------------------------------
    // MESSAGE
    // --------------------------------------

    alert(

        product.name +

        (
            selectedSize
            ? " - " + selectedSize
            : ""
        ) +

        " x " +

        quantity +

        " added to cart!"

    );


    // --------------------------------------
    // GO TO CART
    // --------------------------------------

    window.location.href =
        "index.html";

}
// Update cart icon number

function updateCartCount(){

    let count = 0;


    cart.forEach(item=>{

        count += item.quantity;

    });


    let cartCount =
    document.querySelector(".cart-count");


    if(cartCount){

        cartCount.innerHTML=count;

    }

}


updateCartCount();
